import { expect, test as base } from "@playwright/test";
import type { APIRequestContext, Page } from "@playwright/test";

/** Credentials seeded only inside the disposable full-stack test database. */
export interface TestAccount {
  /** A worker-specific ordinary Django username, never an administrator. */
  username: string;
  /** A fresh random value injected by the Docker entry script for this test run. */
  password: string;
}

/** Reusable browser and account boundaries shared by authentication and job stories. */
interface ApplicationFixtures {
  /** The primary owner for this parallel worker's persisted test jobs. */
  account: TestAccount;
  /** A separate user for access-control checks, with the same ephemeral test password. */
  otherAccount: TestAccount;
  /** A fresh browser page authenticated through the actual login form and API client. */
  signedInPage: Page;
}

/** Sign in through accessible controls so stories exercise session and CSRF handling. */
export async function signInThroughForm(page: Page, account: TestAccount): Promise<void> {
  // A new browser session must enter through the real default screen rather than stored cookies.
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "Sign in", exact: true })).toBeVisible();
  await page.getByRole("textbox", { name: "Username", exact: true }).fill(account.username);
  await page.getByLabel("Password", { exact: true }).fill(account.password);
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Background jobs", exact: true })).toBeVisible();
}

/** Authenticate a separate request context without bypassing Django's real login or CSRF checks. */
export async function signInRequest(request: APIRequestContext, account: TestAccount): Promise<void> {
  // bootstrapResponse sets host-only cookies in this request context before the protected POST.
  const bootstrapResponse = await request.get("/api/csrf/");
  expect(bootstrapResponse.ok()).toBe(true);
  // bootstrapPayload contains the masked header token matching this context's HttpOnly cookie.
  const bootstrapPayload = await bootstrapResponse.json() as { csrfToken: string };
  // loginResponse proves a real ordinary account acquired an authenticated Django session.
  const loginResponse = await request.post("/api/auth/login/", {
    data: account,
    headers: { "X-CSRFToken": bootstrapPayload.csrfToken },
  });
  expect(loginResponse.status()).toBe(200);
  expect((await loginResponse.json()).user.username).toBe(account.username);
}

// The script fixes two Playwright workers; parallelIndex remains stable across browser retries.
export const test = base.extend<ApplicationFixtures>({
  account: async ({ browserName }, provideAccount, testInfo) => {
    // password is generated by the Docker script; absence must not fall back to a shared default.
    const password = process.env.E2E_PASSWORD;
    if (!password) {
      // Running stories without their isolated fixture setup could target the wrong account source.
      throw new Error(`Run ./local-dev.sh test e2e before ${browserName} stories to create disposable test accounts.`);
    }
    await provideAccount({ username: `e2e-worker-${testInfo.parallelIndex}`, password });
  },
  otherAccount: async ({ account }, provideOtherAccount, testInfo) => {
    // The second account has no job submissions of its own in access-control stories.
    await provideOtherAccount({ username: `e2e-other-${testInfo.parallelIndex}`, password: account.password });
  },
  signedInPage: async ({ page, account }, providePage) => {
    // Each test keeps an independent cookie jar even when it reuses this worker's user history.
    await signInThroughForm(page, account);
    await providePage(page);
  },
});

// Keep assertion imports consistent with the custom fixture entry point.
export { expect } from "@playwright/test";
