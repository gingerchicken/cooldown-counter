"""Publish schema output only after a complete, validated generation succeeds."""

import os
import stat
import tempfile
from collections.abc import Callable
from pathlib import Path


def export_schema_atomically(destination: Path, renderer: Callable[[Path], None]) -> bool:
    """Render to a private sibling and replace changed output atomically.

    The renderer owns validation and may raise. Its failures leave the previous
    contract untouched. Returning False means valid output was byte-identical,
    so downstream watchers should not be notified by an unnecessary replacement.
    """
    # destination is normalized once; its parent must exist before a same-filesystem temporary.
    destination = destination.resolve()
    destination.parent.mkdir(parents=True, exist_ok=True)
    # temporary_descriptor and temporary_name belong only to this generation attempt.
    temporary_descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{destination.name}.", suffix=".tmp", dir=destination.parent
    )
    os.close(temporary_descriptor)
    # temporary_path is a sibling so os.replace never crosses a filesystem boundary.
    temporary_path = Path(temporary_name)
    try:
        # Validation must finish before either comparing or publishing the generated bytes.
        renderer(temporary_path)
        # generated_bytes and previous_bytes distinguish an API change from a repeated export.
        generated_bytes = temporary_path.read_bytes()
        previous_bytes = destination.read_bytes() if destination.exists() else None
        if generated_bytes == previous_bytes:
            # Keeping the inode and modification time prevents spurious rebuild loops.
            return False
        # output_mode preserves an existing readable contract or creates normal source permissions.
        output_mode = stat.S_IMODE(destination.stat().st_mode) if destination.exists() else 0o644
        temporary_path.chmod(output_mode)
        os.replace(temporary_path, destination)
        return True
    finally:
        # Failed renders and unchanged successful renders must not leave partial source files.
        temporary_path.unlink(missing_ok=True)
